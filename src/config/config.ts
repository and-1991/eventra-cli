import chalk from "chalk";
import fs from "fs-extra";
import path from "path";

import { MAX_FILE_CHARS, fileLimit } from "../core/fileLimits";
import { normalizeDynamicEvents } from "../analysis/sdk/eventraSdk";
import { EventraConfig, FunctionWrapperConfig, SinkRuleConfig } from "../types";

export const CONFIG_NAME = "eventra.json";

/**
 * Secrets live here instead of `eventra.json`, since the latter is meant to be
 * committed (CI diffs `events`/`functionWrappers` against it via `eventra check`).
 */
export const LOCAL_CONFIG_NAME = "eventra.local.json";

/** Every extension a source file of a JavaScript or TypeScript project can have, ES module and CommonJS variants included. */
export const SOURCE_GLOB = "**/*.{ts,tsx,js,jsx,mjs,cjs,mts,cts}";
const DEFAULT_INCLUDE = [SOURCE_GLOB];

// what a config without `sync.exclude` has always skipped; changing it would change the scan of every
// existing project that never wrote its own list
const DEFAULT_EXCLUDE = ["node_modules", "dist", ".next", ".git"];

/**
 * What `eventra init` writes into a new eventra.json: the default above plus folders and files whose
 * code is not the product. Events fired from a test are not features, and on a large repository the tests
 * alone can double the files scanned. Written out, so it is visible and editable. `build` and `out` are
 * left out on purpose: they are as likely to be a source folder as output.
 */
export const INIT_EXCLUDE = [
  ...DEFAULT_EXCLUDE,
  "coverage",
  // generated by the frameworks: build output and type files, not your code
  ".svelte-kit",
  ".astro",
  ".angular",
  "**/*.{test,spec}.{ts,tsx,js,jsx}",
  "**/__tests__/**",
  "**/__mocks__/**",
];

// A wrong-typed value is not an error that stops the CLI (the file is hand-written), but it must not vanish
// quietly either, least of all when the file is written back: say it once.
const warnedConfig = new Set<string>();
function warnConfig(message: string): void {
  if (warnedConfig.has(message)) return;
  warnedConfig.add(message);
  console.warn(`Eventra: ${message}`);
}

const entries = (count: number): string => `${count} ${count === 1 ? "entry" : "entries"}`;

/** A text setting (`apiKey`, `endpoint`): anything else is reported and left out, not carried into the file. */
function textSetting(name: string, value: unknown): string {
  if (value === undefined) return "";
  if (typeof value !== "string") {
    warnConfig(`"${name}" in eventra.json must be text; it is ignored.`);
    return "";
  }
  return value;
}

function normalizeSinks(sinks: unknown): SinkRuleConfig[] {
  if (sinks === undefined) return [];
  if (!Array.isArray(sinks)) {
    warnConfig(`"sinks" in eventra.json must be a list of rules, for example [{ "preset": "posthog" }]; it is ignored.`);
    return [];
  }
  const valid = sinks.filter(
    (s): s is SinkRuleConfig => typeof s === "object" && s !== null && !Array.isArray(s),
  );
  if (valid.length !== sinks.length) warnConfig(`${entries(sinks.length - valid.length)} of "sinks" in eventra.json ${sinks.length - valid.length === 1 ? "is" : "are"} not an object and ignored.`);
  return valid;
}

/** A list of event names: anything else in its place is reported and dropped, instead of being spread into characters. */
function eventList(value: unknown): string[] {
  if (value === undefined) return [];
  if (!Array.isArray(value)) {
    warnConfig(`"events" in eventra.json must be a list of names; it is ignored.`);
    return [];
  }
  const names = value.filter((item): item is string => typeof item === "string");
  if (names.length !== value.length) warnConfig(`${entries(value.length - names.length)} of "events" in eventra.json ${value.length - names.length === 1 ? "is" : "are"} not a string and ignored.`);
  return names;
}

// every top-level key the CLI itself reads or writes; anything else in eventra.json is the user's and is kept
const KNOWN_KEYS = new Set(["apiKey", "endpoint", "events", "functionWrappers", "plugins", "dynamicEvents", "sinks", "sync"]);
const KNOWN_SYNC_KEYS = new Set(["include", "exclude", "maxFileSize"]);

/** A list of strings from a value that should be one: a lone string counts as a list of one, anything else that is not a string is dropped. */
function stringList(value: unknown): string[] | undefined {
  if (typeof value === "string") return [value];
  if (!Array.isArray(value)) return undefined;
  return value.filter((item): item is string => typeof item === "string");
}

/**
 * Globs are written with `/`. A Windows-style `src\\**\\*.ts` matches nothing for fast-glob (a backslash escapes the
 * next character), which silently emptied the catalog. A `\\` before `*` or `(` cannot be told from an escape, and a
 * folder such as `(group)` after a separator is far likelier than an escaped glob character, so every `\\` is read as `/`.
 */
function globPattern(pattern: string): string {
  // a pattern that already uses `/` is written the POSIX way, and there a backslash is an escape (`app/\\(group\\)/*.ts`)
  return pattern.includes("/") ? pattern : pattern.replace(/\\/g, "/");
}

const warnedPluginEntries = new Set<string | undefined>();

function normalizePlugins(value: unknown): string[] {
  const seen = new Set<string>();
  if (Array.isArray(value)) {
    for (const item of value) {
      // the plugin loader warns about what is in the config; this is what is left of it after the config is read
      if (typeof item !== "string" && !warnedPluginEntries.has(JSON.stringify(item))) {
        warnedPluginEntries.add(JSON.stringify(item));
        console.warn(`Eventra: skipping plugin entry ${JSON.stringify(item)}: a plugin is a package name (a string).`);
      }
    }
  }
  for (const item of stringList(value) ?? []) {
    const trimmed = item.trim();
    if (trimmed) seen.add(trimmed);
  }
  return [...seen];
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export function normalizeConfig(config: Partial<EventraConfig>): EventraConfig {
  const extra: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(config)) {
    if (!KNOWN_KEYS.has(key)) extra[key] = value;
  }
  const extraSync: Record<string, unknown> = {};
  if (isPlainObject(config.sync)) {
    for (const [key, value] of Object.entries(config.sync)) {
      if (!KNOWN_SYNC_KEYS.has(key)) extraSync[key] = value;
    }
  }
  const include = stringList(config.sync?.include);
  const exclude = stringList(config.sync?.exclude);
  for (const [name, raw, list] of [["include", config.sync?.include, include], ["exclude", config.sync?.exclude, exclude]] as const) {
    if (Array.isArray(raw) && list !== undefined && list.length !== raw.length) {
      warnConfig(`${entries(raw.length - list.length)} of "sync.${name}" in eventra.json ${raw.length - list.length === 1 ? "is" : "are"} not a string and ignored.`);
    }
  }

  const rawWrappers: unknown = config.functionWrappers;
  if (rawWrappers !== undefined && !Array.isArray(rawWrappers)) {
    warnConfig(`"functionWrappers" in eventra.json must be a list; it is ignored.`);
  }
  const functionWrappers = (Array.isArray(rawWrappers) ? (rawWrappers as FunctionWrapperConfig[]) : [])
    .filter((w) => typeof w?.name === "string" && w.name)
    .map((w) => ({ name: w.name }));
  if (Array.isArray(rawWrappers) && functionWrappers.length !== rawWrappers.length) {
    warnConfig(`${entries(rawWrappers.length - functionWrappers.length)} of "functionWrappers" in eventra.json ${rawWrappers.length - functionWrappers.length === 1 ? "has" : "have"} no "name" and ignored.`);
  }

  const seen = new Set<string>();
  const uniqueWrappers = functionWrappers.filter((w) => {
    if (seen.has(w.name)) return false;
    seen.add(w.name);
    return true;
  });

  const sinks = normalizeSinks(config.sinks);
  const dynamicEvents = normalizeDynamicEvents(config.dynamicEvents);
  const rawDynamic: unknown = config.dynamicEvents;
  if (rawDynamic !== undefined && !Array.isArray(rawDynamic)) {
    warnConfig(`"dynamicEvents" in eventra.json must be a list of names; it is ignored.`);
  } else if (Array.isArray(rawDynamic)) {
    for (const item of rawDynamic) {
      if (typeof item !== "string" || normalizeDynamicEvents([item]).length === 0) {
        warnConfig(`"dynamicEvents" in eventra.json: ${JSON.stringify(item)} is not a usable event name and is ignored.`);
      }
    }
  }
  const rawLimit: unknown = config.sync?.maxFileSize;
  if (rawLimit !== undefined && fileLimit(rawLimit) === MAX_FILE_CHARS && rawLimit !== MAX_FILE_CHARS) {
    warnConfig(`"sync.maxFileSize" in eventra.json must be a positive whole number of characters; ${MAX_FILE_CHARS} is used.`);
  }

  return {
    ...extra,
    apiKey: textSetting("apiKey", config.apiKey),
    endpoint: textSetting("endpoint", config.endpoint),
    events: eventList(config.events).sort(),
    // plain comparison, not localeCompare: the order in the committed file must
    // not depend on the machine's ICU locale
    functionWrappers: uniqueWrappers.sort((a, b) => (a.name < b.name ? -1 : 1)),
    plugins: normalizePlugins(config.plugins),
    ...(dynamicEvents.length > 0 ? { dynamicEvents } : {}),
    ...(sinks.length > 0 ? { sinks } : {}),
    sync: {
      ...extraSync,
      include: include ? include.map(globPattern) : DEFAULT_INCLUDE,
      exclude: exclude ? exclude.map(globPattern) : DEFAULT_EXCLUDE,
      // kept only when it changes something: a config that never set it stays as it was
      ...(fileLimit(config.sync?.maxFileSize) !== MAX_FILE_CHARS ? { maxFileSize: fileLimit(config.sync?.maxFileSize) } : {}),
    },
  };
}

export async function loadConfig(): Promise<EventraConfig | null> {
  const configPath = path.join(process.cwd(), CONFIG_NAME);
  if (!(await fs.pathExists(configPath))) {
    return null;
  }
  try {
    const config = await fs.readJSON(configPath);
    // a list, a string or null at the top is not a config: do not overwrite it with defaults
    if (!isPlainObject(config)) return null;
    return normalizeConfig(config);
  } catch {
    return null;
  }
}

/**
 * Says why `loadConfig` returned null, for the CLI's error message: a missing
 * file and a malformed one are different problems.
 */
export async function describeConfigProblem(): Promise<string> {
  const configPath = path.join(process.cwd(), CONFIG_NAME);
  if (!(await fs.pathExists(configPath))) return `${CONFIG_NAME} not found`;
  try {
    const raw = await fs.readJSON(configPath);
    if (!isPlainObject(raw)) return `${CONFIG_NAME} must contain a JSON object ({ ... }), not ${Array.isArray(raw) ? "a list" : raw === null ? "null" : `a ${typeof raw}`}`;
    return `${CONFIG_NAME} could not be read`;
  } catch (err) {
    // readJSON only rejects with an Error (ENOENT was ruled out above, the rest is a parse error)
    // a file that cannot be opened (no permission, a folder in its place) is not a file with bad JSON in it
    if (err instanceof SyntaxError) return `${CONFIG_NAME} is not valid JSON: ${err.message}`;
    return `${CONFIG_NAME} could not be read: ${(err as Error).message}`;
  }
}

/**
 * Loads the config for a command that cannot run without it. On failure it
 * prints the reason and sets a non-zero exit code, and returns null, so every
 * command ends the same way when there is no usable config.
 */
export async function requireConfig(): Promise<EventraConfig | null> {
  const config = await loadConfig();
  if (config) {
    warnInlineApiKey(config);
    return config;
  }
  console.error(await describeConfigProblem());
  process.exitCode = 1;
  return null;
}

/**
 * Tells the user when `eventra.json` holds an API key. The file is meant to be committed, so a key in it
 * is readable by everyone with access to the repository. Goes to stderr, never prints the key itself, and
 * says nothing when the field is empty (what `init` writes).
 */
export function warnInlineApiKey(config: EventraConfig): void {
  if (!config.apiKey) return;
  console.error(
    chalk.yellow(
      `${CONFIG_NAME} contains an "apiKey". This file is meant to be committed, so anyone who can read the repository can read the key.\n` +
        `Set "apiKey" to "" and use the EVENTRA_API_KEY environment variable (CI) or ${LOCAL_CONFIG_NAME} (local, gitignored) instead.\n` +
        `If the file was ever committed or pushed, create a new key in the dashboard and revoke this one.`,
    ),
  );
}

/** Writes eventra.json only when its content actually changed (watch mode re-saves often). */
export async function saveConfig(config: EventraConfig): Promise<void> {
  const configPath = path.join(process.cwd(), CONFIG_NAME);
  const next = `${JSON.stringify(normalizeConfig(config), null, 2)}\n`;
  try {
    if ((await fs.readFile(configPath, "utf8")) === next) return;
  } catch {
    // missing or unreadable: write it
  }
  await fs.writeFile(configPath, next);
}

interface LocalSecrets {
  apiKey?: string;
  trustedEndpoint?: string;
}

async function readLocalSecrets(): Promise<LocalSecrets> {
  const localPath = path.join(process.cwd(), LOCAL_CONFIG_NAME);
  if (!(await fs.pathExists(localPath))) return {};
  try {
    const parsed = await fs.readJSON(localPath);
    return {
      apiKey: typeof parsed?.apiKey === "string" && parsed.apiKey ? parsed.apiKey : undefined,
      trustedEndpoint:
        typeof parsed?.trustedEndpoint === "string" && parsed.trustedEndpoint
          ? parsed.trustedEndpoint
          : undefined,
    };
  } catch {
    // an empty or half-written file would otherwise look like "no key" with no explanation
    console.warn(`Eventra: ${LOCAL_CONFIG_NAME} is not valid JSON and is ignored: fix it or delete it.`);
    return {};
  }
}

async function writeLocalSecrets(patch: LocalSecrets): Promise<void> {
  const localPath = path.join(process.cwd(), LOCAL_CONFIG_NAME);
  const next: LocalSecrets = { ...(await readLocalSecrets()), ...patch };
  const out: LocalSecrets = {};
  if (next.apiKey) out.apiKey = next.apiKey;
  if (next.trustedEndpoint) out.trustedEndpoint = next.trustedEndpoint;

  // the file holds an API key: readable by its owner only (the mode applies when it is created; an old
  // file written with the default mode is tightened too)
  await fs.writeFile(localPath, `${JSON.stringify(out, null, 2)}\n`, { mode: 0o600 });
  await fs.chmod(localPath, 0o600).catch(() => undefined);
  await ensureGitignored(LOCAL_CONFIG_NAME);
}

async function ensureGitignored(entry: string): Promise<void> {
  const gitignorePath = path.join(process.cwd(), ".gitignore");
  let content = "";
  if (await fs.pathExists(gitignorePath)) {
    content = await fs.readFile(gitignorePath, "utf8");
    // `eventra.local.json`, `/eventra.local.json` and `**/eventra.local.json` all keep the file out of git
    if (content.split(/\r?\n/).some((line) => [entry, `/${entry}`, `**/${entry}`].includes(line.trim()))) return;
  }
  const needsLeadingNewline = content.length > 0 && !content.endsWith("\n");
  await fs.appendFile(gitignorePath, `${needsLeadingNewline ? "\n" : ""}${entry}\n`);
}

/**
 * Resolves the API key for outbound requests only — never persisted back onto
 * the `EventraConfig` object, so it can't leak into `eventra.json` via `saveConfig`.
 * Priority: `EVENTRA_API_KEY` env var > `eventra.local.json` (gitignored) >
 * legacy inline `apiKey` in `eventra.json` (kept for backward compatibility only).
 */
export async function resolveApiKey(config: EventraConfig): Promise<string | undefined> {
  if (process.env.EVENTRA_API_KEY) return process.env.EVENTRA_API_KEY;
  const { apiKey } = await readLocalSecrets();
  if (apiKey) return apiKey;
  return config.apiKey || undefined;
}

/** Persists an API key to the gitignored local secrets file, never to `eventra.json`. */
export async function saveLocalApiKey(apiKey: string): Promise<void> {
  await writeLocalSecrets({ apiKey });
}

/**
 * The `endpoint` a locally-run `eventra send` last approved, trust-on-first-use
 * style — a non-default `endpoint` sourced from the *committed* `eventra.json`
 * must match this before it's used, so a PR silently changing it can't redirect
 * `send` (and the API key with it) without a human approving it locally once.
 */
export async function getTrustedEndpoint(): Promise<string | undefined> {
  const { trustedEndpoint } = await readLocalSecrets();
  return trustedEndpoint;
}

/** Records `endpoint` as locally approved (see `getTrustedEndpoint`). */
export async function trustEndpoint(endpoint: string): Promise<void> {
  await writeLocalSecrets({ trustedEndpoint: endpoint });
}
